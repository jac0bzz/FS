document.addEventListener('DOMContentLoaded', () => {
    const rigSelect = document.getElementById('rigSelect');
    const rigTitle = document.getElementById('rigTitle');
    const rigImage = document.getElementById('rigImage');
    const rigBadge = document.getElementById('rigBadge');
    const rigDesc = document.getElementById('rigDesc');
    const generalSpecs = document.getElementById('generalSpecs');
    const towerSpecs = document.getElementById('towerSpecs');
    const subSpecs = document.getElementById('subSpecs');

    if (!rigSelect) {
        console.error("The #rigSelect element was not found in the DOM");
        return;
    }

    function loadRigData(id) {
        const data = rigsData[id];
        if (!data) return;

        if (rigTitle) rigTitle.innerText = data.title;
        if (rigBadge) rigBadge.innerText = data.title;
        
        if (rigImage) {
            rigImage.src = data.imagen;
            rigImage.alt = `${data.title} Photo`;
            // Fallback image in case the target image fails to load
            rigImage.onerror = function() {
                this.src = '../Static/Images/2.jpg'; 
            };
        }

        if (rigDesc) rigDesc.innerText = data.description;

        // Load General Specs
        if (generalSpecs) {
            generalSpecs.innerHTML = Object.entries(data.general)
                .map(([k, v]) => `<tr><td>${k}</td><td>${v}</td></tr>`).join('');
        }

        // Load Mast/Tower Specs
        if (towerSpecs) {
            towerSpecs.innerHTML = Object.entries(data.tower)
                .map(([k, v]) => `<tr><td>${k}</td><td>${v}</td></tr>`).join('');
        }

        // Load Substructure Specs
        if (subSpecs) {
            subSpecs.innerHTML = Object.entries(data.substructure)
                .map(([k, v]) => `<tr><td>${k}</td><td>${v}</td></tr>`).join('');
        }
    }

    // Event listener for dropdown changes
    rigSelect.addEventListener('change', (e) => loadRigData(e.target.value));

    // Load default RIG 161
    loadRigData("161");
});